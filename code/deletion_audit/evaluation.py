"""Evaluation: score the public samples, check every request against the output rules, write the report.

Everything in the report is computed from the pipeline that is passed in; nothing is typed by hand.
"""
from __future__ import annotations

from collections import Counter
from datetime import datetime
from pathlib import Path

from .common import REPO_ROOT, case_sort_key
from .models import Dataset
from .pipeline import NO_RESOURCE_NOTE, Pipeline
from .planner import _entry_ops
from .scoring import score_case, summarize
from .verify import verify_row

REPORT_DIR = REPO_ROOT / "evaluation_test"


def _step_key(step: dict) -> tuple:
    return (step["phase"], step["operation"], step["system_id"], step["resource_id"], step["state"],
            step["evidence_id"])


def _score_samples(dataset: Dataset, pipeline: Pipeline) -> tuple[dict, list]:
    """Summary over the public samples, and the samples whose answer differs from the reference."""
    results, differing = [], []
    for request in sorted(dataset.sample_requests, key=lambda r: case_sort_key(r.case_id)):
        gold_status, gold_steps = dataset.sample_output[request.case_id]
        answer = pipeline.answer(request)
        results.append(score_case(answer.status, answer.steps, gold_status, gold_steps))
        predicted = {_step_key(s) for s in answer.steps}
        expected = {_step_key(s) for s in gold_steps}
        missing, extra = sorted(expected - predicted), sorted(predicted - expected)
        if answer.status != gold_status or missing or extra:
            differing.append((request.case_id, gold_status, answer.status, missing, extra))
    return summarize(results), differing


def _check_requests(dataset: Dataset, pipeline: Pipeline) -> dict:
    """Run every evaluation request through the row verifier and count what comes out."""
    times = {f.file_id: f.captured_at for f in dataset.evidence_files}
    times.update({a.activity_id: a.event_time for a in dataset.activity})
    times.update({e.audit_id: e.event_time for e in dataset.audit_log})
    names: dict[str, set[str]] = {}
    for rec in pipeline.index.records:
        names.setdefault(rec.file_id, set()).update((*rec.mentions, *([rec.resource_id] if rec.resource_id else [])))
    systems: dict[str, set[str]] = {}
    for scope in pipeline.index.scopes:
        if scope.system:
            systems.setdefault(scope.file_id, set()).add(scope.system)

    counts: Counter = Counter()
    problems: list[str] = []
    unidentified: list[str] = []
    steps_total = left_out = from_readings = 0
    for request in sorted(dataset.requests, key=lambda r: case_sort_key(r.case_id)):
        answer = pipeline.answer(request)
        counts[answer.status] += 1
        steps_total += len(answer.steps)
        no_resource = answer.status == "COMPLETE" and not answer.steps and answer.note == NO_RESOURCE_NOTE
        if no_resource:
            unidentified.append(request.case_id)
        problems += verify_row(request.case_id, answer.status, answer.steps, request.audit_at, times,
                               allow_unidentified=no_resource, evidence_names=names, evidence_systems=systems)
        if answer.ledger:
            left_out += len(answer.ledger.dropped)
            left_out += sum(1 for e in answer.ledger.entries if _entry_ops(e) is None)
            from_readings += sum(1 for e in answer.ledger.entries
                                 if e.observation is not None and e.observation.kind == "screen_reading")
    return {"counts": counts, "problems": problems, "unidentified": unidentified,
            "steps": steps_total, "left_out": left_out, "from_readings": from_readings}


def _render(dataset: Dataset, samples: dict, differing: list, checks: dict) -> str:
    full, loose, n = samples["full_steps"], samples["identity_steps"], samples["cases"]
    counts, requests = checks["counts"], len(dataset.requests)
    lines = [
        "# Evaluation report",
        "",
        "Generated by the evaluation step (`python code/main.py run`, or `python evaluation_test/run_evaluation.py` on its own) "
        "from a real run of the engine. Every number below comes from that run.",
        "",
        "## What is measured and against what",
        "",
        f"The {n} public samples are the only cases with reference answers (`dataset/sample_output.csv`), so every accuracy "
        f"number is on those {n}. The {requests} evaluation requests have no reference answers; for them the report only "
        "checks the output against the submission contract.",
        "",
        f"## Sample results ({n} cases, {full['gold']} reference steps)",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Case-level deletion_status accuracy | {samples['status_correct']}/{n} ({100 * samples['status_correct'] / n:.1f}%) |",
        f"| Cases with every step exactly right | {samples['cases_exact']}/{n} ({100 * samples['cases_exact'] / n:.1f}%) |",
        f"| Step precision | {full['precision']} ({full['tp']} of {full['pred']} predicted steps are in the reference) |",
        f"| Step recall | {full['recall']} ({full['tp']} of {full['gold']} reference steps found) |",
        f"| Step F1 | {full['f1']} |",
        f"| Step F1 ignoring evidence_id | {loose['f1']} (precision {loose['precision']}, recall {loose['recall']}) |",
        f"| Field accuracy, state, on {samples['matched_steps']} aligned steps | {samples['field_accuracy']['state']} |",
        f"| Field accuracy, evidence_id, on {samples['matched_steps']} aligned steps | {samples['field_accuracy']['evidence_id']} |",
        f"| Sequence accuracy (ordered list identical) | {samples['sequence_exact']}/{n} ({100 * samples['sequence_exact'] / n:.1f}%) |",
        f"| Mean longest-common-subsequence ratio | {samples['mean_lcs_ratio']} |",
        "",
        "Steps are matched on (phase, system_id, resource_id, operation, state, evidence_id). Field accuracy is measured "
        "on steps whose phase, operation, system_id and resource_id match a reference step.",
        "",
        f"### Samples that are not exact ({len(differing)})",
        "",
    ]
    if differing:
        lines += ["| Case | Reference status | Our status | Missing reference steps | Extra steps |",
                  "|---|---|---|---|---|"]
        for case, gold_status, our_status, missing, extra in differing:
            describe = lambda keys: "; ".join(f"{k[1]} {k[3]}" for k in keys) or "-"
            lines.append(f"| {case} | {gold_status} | {our_status} | {describe(missing)} | {describe(extra)} |")
    else:
        lines.append("None.")
    lines += [
        "",
        f"## Run on the {requests} evaluation requests",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Rows produced | {sum(counts.values())} |",
        f"| COMPLETE / INCOMPLETE / NOT_APPLICABLE | {counts['COMPLETE']} / {counts['INCOMPLETE']} / {counts['NOT_APPLICABLE']} |",
        f"| Total steps | {checks['steps']} |",
        f"| Contract problems found by the row verifier | {len(checks['problems'])} |",
        f"| Cases with no identifiable resource (COMPLETE, no steps) | {len(checks['unidentified'])} {checks['unidentified']} |",
        f"| Resources linked to a case but left out of its answer | {checks['left_out']} |",
        f"| Resource states taken from stored screenshot readings | {checks['from_readings']} |",
        "",
    ]
    if checks["problems"]:
        lines += ["Contract problems (first 20):", ""] + [f"* {p}" for p in checks["problems"][:20]] + [""]
    lines += [
        "## Known limits",
        "",
        "* There is no reference answer for the evaluation requests, so accuracy on them is not measured.",
        "* Where the engine cannot prove which case a resource belongs to, it leaves the step out instead of guessing. "
        "This lowers recall, never precision.",
        "* Cases with no identifiable resource are answered COMPLETE with no steps and are listed above.",
        "* The `condition` column of `deletion_rules.csv` is not evaluated; the engine uses the required action per data category.",
        "* Every row is decided by deterministic code; the run itself calls no model. A few resource states come from "
        "stored readings of console screenshots (`code/readings/`), which a model made by viewing the images. "
        "The loader checks each reading against the evidence, and a reading only fills in the state of a resource "
        "that identifiers already tie to the case.",
        "* The stored readings could not be checked against reference answers: none of the public samples involves them. "
        "They are checked only for consistency with the evidence.",
        "",
    ]
    return "\n".join(lines)


def write_report(dataset: Dataset, pipeline: Pipeline, directory: Path | None = None) -> tuple[dict, dict, Path]:
    """Compute the metrics and write them to a NEW timestamped report file.

    Each call creates evaluation_report_<date>_<time>.md next to the earlier ones. An existing file is
    never opened for writing: if two runs land in the same second, a numeric suffix is added.
    Returns (sample summary, request checks, path of the file that was written).
    """
    samples, differing = _score_samples(dataset, pipeline)
    checks = _check_requests(dataset, pipeline)
    text = _render(dataset, samples, differing, checks)

    target_dir = directory or REPORT_DIR
    target_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    attempt = 0
    while True:
        suffix = f"_{attempt}" if attempt else ""
        path = target_dir / f"evaluation_report_{stamp}{suffix}.md"
        try:
            with path.open("x", encoding="utf-8") as handle:     # "x" fails instead of overwriting
                handle.write(text)
            return samples, checks, path
        except FileExistsError:
            attempt += 1
