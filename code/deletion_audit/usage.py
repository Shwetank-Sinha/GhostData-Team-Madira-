"""Usage report: what model usage lay behind the final run, written as a new timestamped Markdown file.

Three separate things are reported, because they are different:
  1. model calls made by the run itself (from the usage ledger; none unless a client was used)
  2. stored screenshot readings that the run loads from a file (made earlier by viewing the images)
  3. API calls made while developing, which are not part of the final run (recorded by hand below)
"""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

from .common import REPO_ROOT
from .readings import DEFAULT_PATH as READINGS_PATH

REPORT_DIR = REPO_ROOT / "evaluation_test"

# Hand-recorded, because these calls happened outside the pipeline (smoke tests while building the clients).
DEVELOPMENT_CALLS = [
    ("Google (Gemini API)", "gemini-3.5-flash", "1 answered", "15 in / 6 out", "free tier, 0 USD billed"),
    ("Google (Gemini API)", "gemini-3.1-flash-lite", "1 answered", "15 in / 11 out", "free tier, 0 USD billed"),
    ("Google (Gemini API)", "gemini-3.8-flash, gemini-3.7-flash, gemini-2.5-flash, gemini-flash-lite-latest",
     "0 answered (daily free-tier quota used up, model closed to new users, or invalid argument)", "none recorded", "0 USD"),
    ("OpenAI", "gpt-4.1-2025-04-14", "0 answered (account has no credit)", "none", "0 USD"),
]


def _row(cells) -> str:
    return "| " + " | ".join(str(c) for c in cells) + " |"


def write_usage_report(ledger_summary: dict, requests: int, readings_path: Path = READINGS_PATH,
                       directory: Path = REPORT_DIR) -> Path:
    """Write a new usage report and return its path. An existing file is never overwritten."""
    total_in = sum(m["input_tokens"] for m in ledger_summary.values())
    total_out = sum(m["output_tokens"] for m in ledger_summary.values())
    calls = sum(m["calls"] for m in ledger_summary.values())

    lines = [
        "# Usage report",
        "",
        "Generated by `python code/main.py run`. It covers the run that produced `output.csv`.",
        "",
        "## 1. Model calls made by the final run",
        "",
    ]
    if ledger_summary:
        lines += [_row(["Provider", "Model", "Calls", "Live", "Cached", "Input tokens", "Output tokens",
                        "Total tokens", "Avg tokens / request"]),
                  _row(["---"] * 9)]
        for model, m in sorted(ledger_summary.items()):
            total = m["input_tokens"] + m["output_tokens"]
            lines.append(_row([m["provider"], model, m["calls"], m["live_calls"], m["cached_calls"],
                               m["input_tokens"], m["output_tokens"], total, f"{total / requests:.1f}"]))
        lines.append(_row(["**All**", "", calls, "", "", total_in, total_out, total_in + total_out,
                           f"{(total_in + total_out) / requests:.1f}"]))
    else:
        lines += ["The run made **no model calls**: 0 calls, 0 input tokens, 0 output tokens, 0 tokens per request, "
                  "0 USD. Every row of `output.csv` is decided by deterministic code.", ""]

    lines += ["", "## 2. Stored screenshot readings loaded by the run", ""]
    if readings_path.is_file():
        data = json.loads(readings_path.read_text(encoding="utf-8"))
        used = data.get("readings", [])
        skipped = data.get("not_determinable", [])
        lines += [
            f"* File: `{readings_path.relative_to(REPO_ROOT).as_posix()}`",
            f"* Read by: {data.get('read_by', 'unknown')} on {data.get('read_on', 'unknown')}, by viewing the screenshot images directly",
            f"* Screenshots viewed: {len({r['file_id'] for r in used} | {r['file_id'] for r in skipped})}; "
            f"readings recorded: {len(used)}; screenshots with no readable state: {len(skipped)}",
            "* Tokens and cost: **not metered**. The coding tool does not report usage per task, so there is no measured "
            "figure. A rough estimate is 10,000 to 15,000 tokens in total (an estimate, not a measurement). "
            "No per-token API charge was made for these readings.",
            "* These readings are loaded from the file on every run; the run does not call a model to produce them.",
        ]
    else:
        lines.append("No readings file is present.")

    lines += ["", "## 3. API calls made while developing (not part of the final run)", "",
              "Recorded by hand. These were small tests of the model clients; none of their output is used in `output.csv`.", "",
              _row(["Provider", "Model", "Result", "Tokens", "Cost"]), _row(["---"] * 5)]
    lines += [_row(item) for item in DEVELOPMENT_CALLS]
    lines += ["", "The clients (`gemini.py`, `openai_client.py`) keep a usage ledger and a cache, so any future live use is "
              "counted in section 1.", ""]

    directory.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    attempt = 0
    while True:
        path = directory / f"usage_report_{stamp}{f'_{attempt}' if attempt else ''}.md"
        try:
            with path.open("x", encoding="utf-8") as handle:
                handle.write("\n".join(lines))
            return path
        except FileExistsError:
            attempt += 1
